//! A caller-configured loopback UDP application loaded by its Java bridge class.

#[path = "../../support/udp.rs"]
mod udp;

use miju_services::{
    Application, BoxError, Lifetime, ServiceSpec,
    jni::{App, BuildError, BuildErrorKind},
    service_fn,
};
use std::{net::SocketAddr, path::PathBuf, sync::Arc};
use tokio::sync::oneshot;

struct UdpApp;

impl App for UdpApp {
    const NAME: &'static str = "miju-jni-udp";
    const VERSION: &'static str = env!("CARGO_PKG_VERSION");

    fn build(args: Vec<String>) -> Result<Application, BuildError> {
        let [address, output] = args.as_slice() else {
            return Err(BuildError::new(
                BuildErrorKind::Usage,
                "expected loopback address and address-file path",
            ));
        };
        let address: SocketAddr = address.parse().map_err(|_| {
            BuildError::new(BuildErrorKind::Configuration, "invalid socket address")
        })?;
        if !address.ip().is_loopback() {
            return Err(BuildError::new(
                BuildErrorKind::Configuration,
                "example accepts only loopback addresses",
            ));
        }
        let output = PathBuf::from(output);
        let (bound, receiver) = oneshot::channel();
        Application::builder()
            .service(
                ServiceSpec::new("udp"),
                service_fn(move |context| {
                    udp::serve(
                        context,
                        address,
                        bound,
                        Arc::new(udp::UdpCounters::default()),
                        |packet, peer, socket, _work| async move {
                            socket.send_to(&packet, peer).await?;
                            Ok::<(), BoxError>(())
                        },
                    )
                }),
            )
            .service(
                ServiceSpec::new("publish-address")
                    .depends_on("udp")
                    .lifetime(Lifetime::Finite),
                service_fn(move |context| async move {
                    let address = receiver.await?;
                    std::fs::write(&output, address.to_string())?;
                    let cleanup = move || async move {
                        std::fs::remove_file(output)?;
                        Ok::<(), BoxError>(())
                    };
                    if let Err(rejected) = context.defer_cleanup("remove address file", cleanup) {
                        rejected.into_cleanup()().await?;
                        if !context.is_stopping() {
                            return Err(std::io::Error::other("cleanup registration closed").into());
                        }
                    }
                    Ok::<(), BoxError>(())
                }),
            )
            .build()
            .map_err(|_| BuildError::new(BuildErrorKind::Startup, "application assembly failed"))
    }
}

// Only this ABI module permits the controlled unsafe generated by export!.
#[allow(unsafe_code)]
mod exports {
    miju_services::jni::export!(class = "com/example/MijuBridge", app = super::UdpApp);
}
